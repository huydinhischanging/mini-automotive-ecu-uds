/* Timer ISR only raises a flag; the real work (ADC, CAN, printf) runs in the
 * main loop so the interrupt stays short and nothing blocks inside it. */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM6)
  {
    if (s_tick10ms)
    {
      s_tickOverruns++;   /* previous 10 ms task has not finished yet */
    }
    s_tick10ms = true;
  }
}

/* printf() -> USART2 -> ST-LINK virtual COM port (115200 8N1) */
